    public static string Tr(string s)
    {
        if (cur == null || s == null) return s;
        if (index == null) { if (!loaded) Init(); if (cur == null || index == null) return s; }
        int i;
        return index.TryGetValue(s, out i) ? cur[i] : s;
    }
