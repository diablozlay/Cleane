    static string SettingsFile { get { return Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "SystemJunkCleaner", "lang.txt"); } }

    static string FromCulture(System.Globalization.CultureInfo ci)
    {
        string n = ci.Name;
        string two = ci.TwoLetterISOLanguageName;
        if (two == "zh")
        {
            if (n.StartsWith("zh-TW") || n.StartsWith("zh-HK") || n.StartsWith("zh-MO") || n.StartsWith("zh-Hant")) return "zh_TW";
            return "zh_CN";
        }
        foreach (var c in Codes) if (c.StartsWith(two + "_")) return c;
        return "en_US";
    }

    public static void Init()
    {
        string code = null;
        try { if (File.Exists(SettingsFile)) code = File.ReadAllText(SettingsFile).Trim(); } catch { }
        if (code == null || Array.IndexOf(Codes, code) < 0)
        {
            try { code = FromCulture(System.Globalization.CultureInfo.CurrentUICulture); } catch { code = "en_US"; }
        }
        Set(code);
    }

    static void Set(string code)
    {
        Code = code; cur = null;
        if (code == "zh_TW") return;
        string[] t;
        if (!Tables.TryGetValue(code, out t))
        {
            switch (code)
            {
                case "cs_CZ": t = T_cs_CZ(); break;
                case "de_DE": t = T_de_DE(); break;
                case "en_US": t = T_en_US(); break;
                case "es_ES": t = T_es_ES(); break;
                case "fr_FR": t = T_fr_FR(); break;
                case "hu_HU": t = T_hu_HU(); break;
                case "it_IT": t = T_it_IT(); break;
                case "ja_JP": t = T_ja_JP(); break;
                case "ko_KR": t = T_ko_KR(); break;
                case "pl_PL": t = T_pl_PL(); break;
                case "pt_PT": t = T_pt_PT(); break;
                case "ru_RU": t = T_ru_RU(); break;
                case "tr_TR": t = T_tr_TR(); break;
                case "zh_CN": t = T_zh_CN(); break;
                default: t = null; break;
            }
            if (t != null) Tables[code] = t;
        }
        if (t == null || t.Length != Keys.Length) return;
        if (index == null)
        {
            index = new Dictionary<string, int>();
            for (int i = 0; i < Keys.Length; i++) if (!index.ContainsKey(Keys[i])) index[Keys[i]] = i;
        }
        cur = t;
    }

    public static void Save(string code)
    {
        try { Directory.CreateDirectory(Path.GetDirectoryName(SettingsFile)); File.WriteAllText(SettingsFile, code); } catch { }
    }

    public static string Display(string code)
    {
        int i = Array.IndexOf(Codes, code);
        return i < 0 ? code : Codes[i] + " " + Names[i];
    }

